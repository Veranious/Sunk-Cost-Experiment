function LiveTrialTable(action, trialNum, Offer, Revised, ReviseTime, NewOffer, ...
                      InitLat, ChoiceLat, Accepted, TimeWaited, TimeWaitedRev, Rewarded, RewardDelta, EarlyWithdrawal, ChoiceOmission)

persistent PlotHandle TableHandle
persistent ElapsedText TrialTimeText RewardAmtText
persistent EarlyWithdrawalText ChoiceOmissionText
persistent TrialData RewardAmt EarlyWithdrawalCount ChoiceOmissionCount
persistent StartTime LastCallTime
persistent UpdateTimer


switch action
    case 'init'

        TrialData = {};
        RewardAmt = 0;
        EarlyWithdrawalCount = 0;
        ChoiceOmissionCount = 0;
        StartTime = tic;
        LastCallTime = tic;

        % Create window
        PlotHandle = figure( ...
            'Name', 'Trial Monitor', ...
            'NumberTitle', 'off', ...
            'MenuBar', 'none', ...
            'ToolBar', 'none', ...
            'Color', [0.94 0.94 0.94], ...
            'Position', [300 300 1100 450]);


        % Global elapsed time
        uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', 'Elapsed:', ...
            'Units', 'normalized', ...
            'Position', [0.02 0.89 0.08 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));
        ElapsedText = uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', '00:00:00', ...
            'Units', 'normalized', ...
            'Position', [0.10 0.89 0.18 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        % Trial timer
        uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', 'Trial Time:', ...
            'Units', 'normalized', ...
            'Position', [0.34 0.89 0.11 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));
        TrialTimeText = uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', '0.00 s', ...
            'Units', 'normalized', ...
            'Position', [0.44 0.89 0.15 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        % Reward Amount
        uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', 'Reward Delivered (uL):', ...
            'Units', 'normalized', ...
            'Position', [0.64 0.89 0.21 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));
        RewardAmtText = uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', '0', ...
            'Units', 'normalized', ...
            'Position', [0.82 0.89 0.15 0.06], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));      

        % Early Withdrawals
        uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', 'Early Withdrawals:', ...
            'Units', 'normalized', ...
            'Position', [0.02 0.83 0.16 0.05], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        EarlyWithdrawalText = uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', '0', ...
            'Units', 'normalized', ...
            'Position', [0.17 0.83 0.08 0.05], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        % Choice Omissions
        uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', 'Choice Omissions:', ...
            'Units', 'normalized', ...
            'Position', [0.34 0.83 0.16 0.05], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        ChoiceOmissionText = uicontrol(PlotHandle, ...
            'Style', 'text', ...
            'String', '0', ...
            'Units', 'normalized', ...
            'Position', [0.49 0.83 0.08 0.05], ...
            'FontSize', 11, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'left', ...
            'BackgroundColor', get(PlotHandle, 'Color'));

        % Initialize Table
        ColumnNames = { ...
            'Trial No.', ...
            'Offer', ...
            'Revised?', ...
            'Revise Time', ...
            'New Offer', ...
            'Init. Lat.', ...
            'Choice Lat.', ...
            'Accepted?', ...
            'Time Waited (Initial Period)', ...
            'Time Waited (Revised Period)', ...
            'Rewarded?'};
        TableHandle = uitable(PlotHandle, ...
            'Data', TrialData, ...
            'ColumnName', ColumnNames, ...
            'ColumnEditable', false(1,11), ...
            'Units', 'normalized', ...
            'Position', [0.02 0.05 0.96 0.74], ...
            'RowName', [], ...
            'FontSize', 10);

        % Timer to update the clocks
        UpdateTimer = timer( ...
            'ExecutionMode', 'fixedRate', ...
            'Period', 1, ...
            'TimerFcn', @UpdateDisplay);

        start(UpdateTimer);

    case 'update'

        % Window was never created or was closed - recreate it
        if isempty(PlotHandle) || ~isvalid(PlotHandle)
            LiveTrialTable('init');
        end

        % Add trial to the table
        NewRow = { ...
            trialNum, ...
            Offer, ...
            Revised, ...
            ReviseTime, ...
            NewOffer, ...
            InitLat, ...
            ChoiceLat, ...
            Accepted, ...
            TimeWaited, ...
            TimeWaitedRev, ...
            Rewarded};

        if isempty(TrialData)
            TrialData = NewRow; % First trial
        else
            row = find(cell2mat(TrialData(:,1)) == trialNum, 1);
            if isempty(row)
                TrialData = [NewRow; TrialData]; % New trial: add it to the top
            else
                TrialData(row,:) = NewRow; % Existing trial: update that row
            end
        end
        TableHandle.Data = TrialData;

        LastCallTime = tic;

        RewardAmt = RewardAmt + RewardDelta;
        if EarlyWithdrawal
            EarlyWithdrawalCount = EarlyWithdrawalCount + 1;
        end
        if ChoiceOmission
            ChoiceOmissionCount = ChoiceOmissionCount + 1;
        end
        RewardAmtText.String = num2str(RewardAmt);
        EarlyWithdrawalText.String = num2str(EarlyWithdrawalCount);
        ChoiceOmissionText.String = num2str(ChoiceOmissionCount);

        drawnow;


    otherwise
        error('LiveTrialTable: unknown action ''%s''. Use ''init'' or ''update''.', action);

end


% TIMER UPDATE
function UpdateDisplay(~, ~)
    if isempty(PlotHandle) || ~isvalid(PlotHandle)
        return
    end

    % Total elapsed time
    ElapsedSeconds = toc(StartTime);
    % Time since last trial
    TrialSeconds = toc(LastCallTime);

    ElapsedText.String = FormatTime(ElapsedSeconds);
    TrialTimeText.String = sprintf('%.0f s', TrialSeconds);

    drawnow limitrate;
end


% FORMAT TIME
function String = FormatTime(Seconds)
    Hours = floor(Seconds / 3600);
    Minutes = floor(mod(Seconds, 3600) / 60);
    Secs = floor(mod(Seconds, 60));

    String = sprintf('%02d:%02d:%02d', Hours, Minutes, Secs);
end

end
